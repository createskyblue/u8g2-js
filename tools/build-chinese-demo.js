#!/usr/bin/env node
/**
 * build-chinese-demo.js
 *
 * Bundle demo/chinese-fonts-demo.js + the whole src/ library + the 4 full-CJK
 * fonts into ONE self-contained HTML file (demo/chinese-fonts-demo.html) that
 * opens straight from file://. Same technique as build-demo.js: ES modules are
 * concatenated dependency-first with import/export stripped.
 *
 *   node tools/build-chinese-demo.js
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEMO = join(ROOT, 'demo');

function parseImportSpecs(code) {
  const specs = [];
  const re = /^(?:import\s+[^;]+?\s+from|export\s*\{[^}]*\}\s*from)\s*['"]([^'"]+)['"];/gm;
  let m;
  while ((m = re.exec(code))) specs.push(m[1]);
  return specs;
}

function collect(file, seen, order) {
  file = resolve(file);
  if (seen.has(file)) return;
  seen.add(file);
  const code = readFileSync(file, 'utf8');
  for (const spec of parseImportSpecs(code)) {
    const target = resolve(dirname(file), spec);
    if (extname(target).toLowerCase() !== '.js') continue;
    if (!seen.has(target)) collect(target, seen, order);
  }
  order.push(file);
}

function stripModule(code, file) {
  let out = code
    .replace(/^import\s+[^;]+?\s+from\s+['"][^'"]+['"];\s*/gm, '')
    .replace(/^export\s*\{[^}]*\}\s*from\s*['"][^'"]+['"];\s*/gm, '')
    .replace(/^export\s*\{[^}]*\};\s*/gm, '')
    .replace(/^export\s+default\s+/gm, '')
    .replace(/^export\s+(const|let|var|function|class|async\s+function)\s+/gm, '$1 ');
  return `/* ---- ${file.replace(ROOT + '\\\\', '').replace(ROOT + '/', '')} ---- */\n${out}\n`;
}

function main() {
  const seen = new Set();
  const order = [];
  collect(join(DEMO, 'chinese-fonts-demo.js'), seen, order);

  let bundle = '/* u8g2-js Chinese-font test page (generated by tools/build-chinese-demo.js) */\n';
  for (const file of order) {
    bundle += stripModule(readFileSync(file, 'utf8'), file);
  }

  let html = readFileSync(join(DEMO, 'chinese-fonts-demo.html'), 'utf8');
  html = html.replace(
    '<script type="module" src="chinese-fonts-demo.js"></script>',
    '<script type="module">\n' + bundle + '\n</script>',
  );
  html = html.replace(
    '<title>u8g2-js · 中文全字库测试</title>',
    '<title>u8g2-js · 中文全字库测试 (standalone)</title>',
  );

  const outFile = join(DEMO, 'chinese-fonts-demo.html');
  writeFileSync(outFile, html);
  console.log(`wrote ${outFile} (${(html.length / 1024).toFixed(0)} KB, ${order.length} modules)`);
}

main();

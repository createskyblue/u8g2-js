# 中文标点 + 常用符号（含 Latin-1 符号 ° · × ÷ ± 等，filter_ascii=false 时保留）
PUNCT_AND_SYMBOLS = (
    "，。！？：；、（）【】《》〈〉「」『』“”‘’…—～·"
    "·℃°％‰×÷±≠≤≥＝＜＞"
    "□△○●◇◆★☆→←↑↓↔"
    "①②③④⑤⑥⑦⑧⑨⑩"
    "①②③④⑤⑥⑦⑧⑨⑩"
    "＊＃＆＠￥＄％"
)

# ASCII（0x20-0x7E）由 map_include_ascii=true 提供，这里只放需要保留的 Latin-1 补充
LATIN_EXTRA = "°·×÷±℃"

CHARSET = COMMON_CJK + PUNCT_AND_SYMBOLS + LATIN_EXTRA


def build_config(size_px, out_dir):
    return {
        "font_name": "chinese",
        "font_path": TOOL_FONT,
        "font_dpi": 72,
        "font_size_px": size_px,
        "font_spacing_percent": 100,
        "filter_ascii": False,
        "map_include_ascii": True,
        "output_dir": out_dir,
        "custom_chars": CHARSET,
    }


def main():
    for size in (12, 16, 24):
        out_dir = os.path.join(HERE, "out", f"cn{size}")
        cfg = build_config(size, out_dir)
        path = os.path.join(HERE, f"config{size}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(cfg, f, ensure_ascii=False, indent=2)
        n = len(set(CHARSET))
        print(f"config{size}.json -> {n} 个唯一字符, output_dir={out_dir}")


if __name__ == "__main__":
    main()
